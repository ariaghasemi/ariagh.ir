async function cp(from, to) {
  await mkdir(dirname(out(to)), { recursive: true });
  await copyFile(nm(from), out(to));
  console.log(`  ✓ ${to}`);
}

console.log('Vendoring fonts…');
for (const [from, to] of FONT_FILES) await cp(from, to);

console.log('Vendoring scripts…');
for (const [from, to] of JS_FILES) await cp(from, to);

await writeFile(out('fonts.css'), fontsCss, 'utf8');
console.log('  ✓ fonts.css');
console.log('Done.');
