/**
 * Copies third-party runtime assets out of node_modules into assets/vendor/
 * so the whole site + every sample is self-hosted (no CDN, no build step).
 *
 *   npm run vendor
 */
import { mkdir, copyFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = (p) => join(root, 'node_modules', p);
const out = (p) => join(root, 'assets', 'vendor', p);

const FONT_FILES = [
  ['@fontsource-variable/vazirmatn/files/vazirmatn-arabic-wght-normal.woff2', 'fonts/vazirmatn-arabic.woff2'],
  ['@fontsource-variable/vazirmatn/files/vazirmatn-latin-wght-normal.woff2', 'fonts/vazirmatn-latin.woff2'],
  ['@fontsource-variable/vazirmatn/files/vazirmatn-latin-ext-wght-normal.woff2', 'fonts/vazirmatn-latin-ext.woff2'],
  ['@fontsource/instrument-serif/files/instrument-serif-latin-400-normal.woff2', 'fonts/instrument-serif-latin.woff2'],
  ['@fontsource/instrument-serif/files/instrument-serif-latin-400-italic.woff2', 'fonts/instrument-serif-latin-italic.woff2'],
];

const JS_FILES = [
  ['gsap/dist/gsap.min.js', 'gsap.min.js'],
  ['gsap/dist/ScrollTrigger.min.js', 'ScrollTrigger.min.js'],
];

