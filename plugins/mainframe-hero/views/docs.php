			<p>مرورگرها پخشِ خودکارِ ویدیوی صدادار را مسدود می‌کنند، و پخشِ خودکارِ بی‌صدا هم در تلفن همراه با تنظیماتِ ذخیرهٔ داده خاموش می‌شود. گذشته از این، پخشِ خودکارِ یک ویدیوی پس‌زمینهٔ تمام‌صفحه بارِ شبکه و باتریِ سنگینی دارد که برای یک جلوهٔ تزیینی توجیه ندارد. راهِ این طرح این است: ویدیو یک بار تا حدی بارگیری می‌شود تا یک فریم نشان دهد، و بعد کاملاً در اختیارِ اشاره‌گر قرار می‌گیرد.</p>

