			<h3>فرمول</h3>
			<div class="mfh-formula">
				<p class="mfh-formula__line">جابه‌جایی = مکانِ فعلی &minus; مکانِ پیشین</p>
				<p class="mfh-formula__line">افزونگی = ( جابه‌جایی &divide; عرضِ صفحه ) &times; حساسیت &times; زمانِ کل</p>
				<p class="mfh-formula__line">زمانِ هدف = محدودشده میانِ صفر و زمانِ کل ( زمانِ فعلی + افزونگی )</p>
			</div>
			<p>مقدارِ پیش‌فرضِ حساسیت <code>۰/۸</code> است. یعنی برای دیدنِ کلِ ویدیو باید نشانگر را حدودِ یک و یک‌چهارمِ عرضِ صفحه حرکت دهید. این عدد عمداً کمتر از یک است تا ویدیو «سنگین» به نظر برسد و با یک تکانِ کوچکِ مچ، کلِ فیلم پیموده نشود.</p>

			<h3>یک نکتهٔ مهم: فقط یک جست‌وجو در جریان</h3>
			<p>رویدادِ حرکتِ اشاره‌گر ده‌ها بار در ثانیه اجرا می‌شود. اگر هر بار مستقیماً زمان را ست می‌کردیم، صف درخواستِ رمزگشایی پر می‌شد و ویدیو لکنت پیدا می‌کرد. این پیاده‌سازی یک پرچم نگه می‌دارد: تا وقتی جست‌وجویِ قبلی تمام نشده، درخواستِ تازه‌ای فرستاده نمی‌شود، اما آخرین مکان در حافظه می‌ماند. به محض آن‌که رویدادِ «جست‌وجو پایان یافت» برسد، همان آخرین مکان اعمال می‌شود. نتیجه این است که هرچه تندتر حرکت کنید، ویدیو نرم‌تر می‌شود — چون درخواست‌ها یکی‌یکی و کامل انجام می‌شوند.</p>

			<div class="mfh-note mfh-note--tip">
				<p class="mfh-note__k">لغزشِ نمایی</p>
				<p>اگر گزینهٔ لغزش را بیش از صفر کنید، زمانِ هدف به جای آن‌که مستقیماً ست شود، با گام‌هایی به سمتِ آن می‌رود: هر بار بخشی از فاصلهٔ باقی‌مانده طی می‌شود. مقدارِ کوچک یعنی حرکتِ نرم و کش‌دار؛ مقدارِ بزرگ یعنی پاسخِ تند. پیش‌فرضِ این طرح <code>۰/۲۵</code> است.</p>
			</div>

			<h3>چرا فریمِ نخست گاهی خالی است و چه طور درست می‌شود</h3>
			<p>یک ویدیو تا وقتی چیزی از آن بارگیری نشده، هیچ فریمی برای نمایش ندارد — حتی اگر زمانِ آن روی صفر باشد. سه ابزار در افزونه این را حل می‌کند:</p>
			<ul class="mfh-list">
				<li><strong>تصویرِ جلد:</strong> یک عکس که پیش از ویدیو نشان داده می‌شود و همیشه یک تصویر روی صفحه هست.</li>
				<li><strong>برشِ خودکارِ زمان:</strong> اگر تصویری انتخاب نکنید، افزونه به نشانیِ ویدیو عبارتِ <code>#t=0.1</code> را می‌افزاید. مرورگرها این را می‌فهمند و همان فریمِ یک‌دهمِ ثانیه را به عنوانِ جلد می‌گیرند. فریمِ صفرِ بسیاری از فیلم‌ها سیاه است؛ یک‌دهمِ ثانیه جلوتر معمولاً تصویر واقعی دارد.</li>
				<li><strong>تلنگرِ آغاز:</strong> به محض آن‌که اطلاعاتِ ویدیو در دسترس آمد، زمان روی <code>۰/۰۱</code> ست می‌شود. این عددِ کوچک مرورگر را وادار می‌کند یک فریم را رمزگشایی و نقاشی کند، بی‌آن‌که ویدیو واقعاً پخش شود.</li>
			</ul>

			<h3>محور، وارونگی و دور زدن</h3>
			<ul class="mfh-list">
				<li><strong>محور:</strong> پیش‌فرض افقی است، یعنی حرکتِ راست و چپِ اشاره‌گر. اگر عمودی را برگزینید، حرکتِ بالا و پایین به کار می‌افتد — برای صفحه‌هایی که اسکرولِ عمودی دارند و می‌خواهید حسِ دیگری بدهید.</li>
				<li><strong>وارونگی:</strong> جهت را برعکس می‌کند. اگر ویدیو در جهتِ نادرستی حرکت می‌کرد، همین یک گزینه آن را درست می‌کند.</li>
				<li><strong>دور زدن:</strong> وقتی به انتها برسید، به آغاز برمی‌گردد و برعکس. بی‌آن‌که فعال باشد، ویدیو در دو سر متوقف می‌ماند و باید نشانگر را برگردانید.</li>
			</ul>

